"""The web interface's language: English (the source text) or German.

Only the interface is translated (buttons, headings, messages, feedback comments). Words, forms, tasks, questions,
examples, grammar explanations and the verdicts "richtig" / "fast richtig" / "falsch" stay German in both languages.

The language comes from the signed-in user's profile (users.ui_lang); a middleware in app/main.py sets it per
request in a context variable, so templates (`_`) and Python messages (`t`) read the same value without passing it
around. A text written at request time (a stored feedback comment) keeps the language it was written in.

Catalog: English source text -> German. A text missing from it is shown in English; tests/test_i18n.py fails on any
`_()` / `t()` text in the code that has no German entry.
"""

from __future__ import annotations

from contextvars import ContextVar

LANGS = {"en": "English", "de": "Deutsch"}
DEFAULT = "en"

_lang: ContextVar[str] = ContextVar("ui_lang", default=DEFAULT)


def use(lang: str) -> None:
    """Set the language for the rest of this request (an unknown code falls back to English)."""
    _lang.set(lang if lang in LANGS else DEFAULT)


def current() -> str:
    return _lang.get()


def t(text: str, /, **values) -> str:
    """`text` in the current language, then `{name}` placeholders filled from `values` (as plain data)."""
    out = DE.get(text, text) if _lang.get() == "de" else text
    return out.format(**values) if values else out


